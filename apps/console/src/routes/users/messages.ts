export type UsersMessageKey = (typeof USERS_KEYS)[number];

export const usersMessages = sectionCatalogue(USERS_KEYS);

/** The section's own lookup: a staff screen that reaches for another section's string does not compile. */
export function useUsersT(): (key: UsersMessageKey) => string {
  const { locale } = useLocale();
  return (key) => usersMessages[locale][key];
}
