export type CourierMessageKey = (typeof COURIER_KEYS)[number];

export const courierMessages = sectionCatalogue(COURIER_KEYS);
export const courierEn = courierMessages.en;

/**
 * The courier section's lookup, closing over the locale from context.
 *
 * A narrow key type, like the other sections' hooks: a courier screen that reaches for a
 * payroll string should not compile.
 */
export function useCourierT(): (key: CourierMessageKey) => string {
  const { locale } = useLocale();
  return (key) => courierMessages[locale][key];
}
