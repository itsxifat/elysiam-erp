import { Button, Money, PermissionGate, takaToPoisha, type UploadedFile } from '@elysium/ui';
import { useMutation, useQuery } from '@tanstack/react-query';
import { Link, useNavigate } from '@tanstack/react-router';
import { useState } from 'react';

import { ApiError } from '../../api.js';
import { useAbility } from '../../auth/session.js';
import { useT } from '../../i18n/locale.js';
import { DEFAULT_PAGE_SIZE } from '../../lib/table-search.js';
import { listLocations } from '../stock/api.js';
import { createDraft, createEntry, listSupplierOptions } from '../supply/api.js';
import {
  attachImage,
  createProduct,
  listAttributes,
  listCategories,
  type CatalogProduct,
} from './api.js';
import { ChipGroup, Field, PhotoUploader } from './parts.js';
import { slugify } from './slug.js';
import { parseQty, variantRows, type VariantRow } from './variant-grid.js';

/**
 * New product, in one form (plan `catalog-stock-ux`, D-421, D-426).
 *
 * Name, category and price; then the sizes and colours as chips, which draw the
 * variant grid underneath. Each row of the grid can take its own price and an opening
 * quantity. One button creates the product with every SKU (codes generated by the
 * server), attaches the photos, and — when quantities were entered — receives that
 * stock from the chosen supplier at the cost per piece, through the same supply entry
 * the Supply screen posts (invariant 5: purchase cost enters only there; D-421).
 *
 * Active by default (D-426): an owner adding a product means to sell it, and a draft
 * is invisible to the order desk and the till.
 *
 * Every price is typed in taka and converted by `takaToPoisha`, integer arithmetic.
 */
export function CatalogNewProductPage() {
  const ability = useAbility();
  const t = useT();
  const navigate = useNavigate();

  const mayWrite = ability.can('create', 'Catalog');
  const mayReceive = ability.can('create', 'Supply');
  const mayPrice = ability.can('read', 'Cost');

  const [name, setName] = useState('');
  const [categoryId, setCategoryId] = useState('');
  const [taka, setTaka] = useState('');
  const [status, setStatus] = useState<'draft' | 'active'>('active');
  const [description, setDescription] = useState('');
  const [chosen, setChosen] = useState<Record<string, string[]>>({});
  const [rowPrice, setRowPrice] = useState<Record<string, string>>({});
  const [rowQty, setRowQty] = useState<Record<string, string>>({});
  const [locationId, setLocationId] = useState('');
  const [supplierId, setSupplierId] = useState('');
  const [costTaka, setCostTaka] = useState('');
  const [photos, setPhotos] = useState<UploadedFile[]>([]);
  const [created, setCreated] = useState<CatalogProduct | null>(null);

  const categories = useQuery({
    queryKey: ['catalog', 'categories'],
    queryFn: listCategories,
    enabled: mayWrite,
    staleTime: 5 * 60_000,
  });
  const attributes = useQuery({
    queryKey: ['catalog', 'attributes'],
    queryFn: listAttributes,
    enabled: mayWrite,
    staleTime: 5 * 60_000,
  });
  const locations = useQuery({
    queryKey: ['stock', 'locations'],
    queryFn: listLocations,
    enabled: mayWrite && mayReceive,
    staleTime: 5 * 60_000,
  });
  const suppliers = useQuery({
    queryKey: ['supply', 'suppliers', 'options'],
    queryFn: listSupplierOptions,
    enabled: mayWrite && mayReceive,
    staleTime: 5 * 60_000,
  });

  // Size before colour before the rest: the order the codes read in (`…-XL-RED`).
  const ordered = (attributes.data?.items ?? [])
    .filter((attribute) => attribute.isVariant && attribute.values.length > 0)
    .sort((a, b) => rank(a.kind) - rank(b.kind) || a.position - b.position);
  const choice = ordered.map((axis) => ({
    attributeId: axis.id,
    values: axis.values
      .filter((value) => (chosen[axis.id] ?? []).includes(value.id))
      .map((value) => ({ id: value.id, label: value.label })),
  }));
  const rows = variantRows(choice);

  const pricePoisha = takaToPoisha(taka);
  const costPoisha = takaToPoisha(costTaka);
  const receivable = (locations.data?.items ?? []).filter(
    (location) =>
      location.isActive && (location.kind === 'warehouse' || location.kind === 'showroom'),
  );
  const chosenLocation =
    locationId !== '' ? locationId : (receivable.find((l) => l.kind === 'warehouse')?.id ?? '');

  const priceProblem = rows.some(
    (row) =>
      (rowPrice[row.key] ?? '').trim() !== '' && takaToPoisha(rowPrice[row.key] ?? '') === null,
  );
  const qtyProblem = rows.some(
    (row) => (rowQty[row.key] ?? '').trim() !== '' && parseQty(rowQty[row.key] ?? '') === null,
  );
  const stockLines = rows.flatMap((row) => {
    const qty = parseQty(rowQty[row.key] ?? '');
    return qty === null ? [] : [{ row, qty }];
  });
  const wantsStock = mayReceive && stockLines.length > 0;
  const stockReady =
    !wantsStock ||
    (supplierId !== '' && chosenLocation !== '' && (!mayPrice || costPoisha !== null));
  const units = stockLines.reduce((sum, entry) => sum + entry.qty, 0);

  const ready =
    name.trim() !== '' && pricePoisha !== null && !priceProblem && !qtyProblem && stockReady;

  const save = useMutation({
    mutationFn: async () => {
      const product =
        created ??
        (await createProduct({
          name: name.trim(),
          slug: slugify(name),
          categoryId: categoryId === '' ? undefined : categoryId,
          description: description.trim() === '' ? undefined : description.trim(),
          pricePoisha: pricePoisha ?? '',
          status,
          axes: choice
            .filter((axis) => axis.values.length > 0)
            .map((axis) => ({
              attributeId: axis.attributeId,
              valueIds: axis.values.map((value) => value.id),
            })),
          variantPrices: rows.flatMap((row) => {
            const own = takaToPoisha(rowPrice[row.key] ?? '');
            return own === null || own === pricePoisha
              ? []
              : [{ valueIds: row.valueIds, pricePoisha: own }];
          }),
        }));
      // Kept, so a retry after a failed photo or stock step does not create it twice.
      setCreated(product);

      for (const photo of photos) {
        await attachImage(product.id, { fileId: photo.id });
      }
      setPhotos([]);

      if (wantsStock) {
        const lines = stockLines.flatMap((entry) => {
          const skuId = skuFor(product, entry.row);
          return skuId === undefined ? [] : [{ skuId, qty: entry.qty }];
        });
        if (mayPrice) {
          await createEntry({
            supplyId: crypto.randomUUID(),
            supplierId,
            locationId: chosenLocation,
            memo: t('cs.new.openingMemo'),
            lines: lines.map((line) => ({ ...line, unitCostPoisha: costPoisha ?? '0' })),
          });
        } else {
          await createDraft({
            draftId: crypto.randomUUID(),
            supplierId,
            locationId: chosenLocation,
            lines,
          });
        }
      }
      return product;
    },
    onSuccess: (product) =>
      void navigate({ to: '/catalog/$productId', params: { productId: product.id } }),
  });

  const control =
    'h-8 rounded-md border border-border bg-background px-2 text-sm outline-none focus-visible:ring-2 focus-visible:ring-ring';

  return (
    <PermissionGate
      allowed={mayWrite}
      explain={{ title: t('catalog.deniedTitle'), detail: t('catalog.deniedDetail') }}
    >
      <div className="max-w-3xl space-y-6">
        <header className="space-y-1">
          <h1 className="text-lg font-semibold tracking-tight">{t('catalog.newProduct')}</h1>
          <p className="text-sm text-muted-foreground">{t('cs.new.help')}</p>
        </header>

        <section aria-labelledby="basics-heading" className="space-y-3">
          <h2 id="basics-heading" className="text-sm font-semibold">
            {t('cs.new.basics')}
          </h2>
          <div className="grid gap-3 sm:grid-cols-2">
            <Field label={t('catalog.productName')} className="sm:col-span-2">
              <input
                value={name}
                maxLength={200}
                onChange={(event) => setName(event.target.value)}
                className={control}
              />
            </Field>
            <Field label={t('catalog.productCategory')}>
              <select
                value={categoryId}
                onChange={(event) => setCategoryId(event.target.value)}
                className={control}
              >
                <option value="">{t('cs.noCategory')}</option>
                {(categories.data?.items ?? [])
                  .filter((category) => category.isActive)
                  .map((category) => (
                    <option key={category.id} value={category.id}>
                      {'  '.repeat(category.depth)}
                      {category.name}
                    </option>
                  ))}
              </select>
            </Field>
            <Field label={t('cs.sellingPrice')}>
              <input
                inputMode="decimal"
                value={taka}
                onChange={(event) => setTaka(event.target.value)}
                aria-invalid={taka.trim() !== '' && pricePoisha === null}
                className={`${control} text-right tabular-nums`}
              />
            </Field>
            <Field label={t('catalog.productStatus')}>
              <select
                value={status}
                onChange={(event) => setStatus(event.target.value as 'draft' | 'active')}
                className={control}
              >
                <option value="active">{t('cs.status.activeHelp')}</option>
                <option value="draft">{t('cs.status.draftHelp')}</option>
              </select>
            </Field>
            <Field label={t('cs.description')} className="sm:col-span-2">
              <textarea
                value={description}
                maxLength={4000}
                rows={2}
                onChange={(event) => setDescription(event.target.value)}
                className="rounded-md border border-border bg-background px-2 py-1.5 text-sm outline-none focus-visible:ring-2 focus-visible:ring-ring"
              />
            </Field>
          </div>
        </section>

        <section aria-labelledby="variants-heading" className="space-y-3">
          <div className="flex items-baseline justify-between gap-3">
            <h2 id="variants-heading" className="text-sm font-semibold">
              {t('cs.new.sizesColours')}
            </h2>
            <Link to="/catalog/structure" className="text-xs underline underline-offset-4">
              {t('cs.manageLists')}
            </Link>
          </div>
          {ordered.length === 0 && attributes.isSuccess ? (
            <p className="text-sm text-muted-foreground">{t('cs.new.noLists')}</p>
          ) : null}
          {ordered.map((axis) => (
            <ChipGroup
              key={axis.id}
              legend={axis.name}
              values={axis.values}
              chosen={chosen[axis.id] ?? []}
              onToggle={(valueId) =>
                setChosen((current) => {
                  const list = current[axis.id] ?? [];
                  return {
                    ...current,
                    [axis.id]: list.includes(valueId)
                      ? list.filter((id) => id !== valueId)
                      : [...list, valueId],
                  };
                })
              }
            />
          ))}

          <table className="w-full text-sm">
            <caption className="sr-only">{t('cs.new.grid')}</caption>
            <thead>
              <tr className="border-b border-border text-left text-xs text-muted-foreground">
                <th scope="col" className="py-1.5">
                  {t('cs.col.variant')}
                </th>
                <th scope="col" className="w-36 py-1.5 text-right">
                  {t('cs.col.price')}
                </th>
                {mayReceive ? (
                  <th scope="col" className="w-32 py-1.5 text-right">
                    {t('cs.col.openingQty')}
                  </th>
                ) : null}
              </tr>
            </thead>
            <tbody>
              {rows.map((row, index) => (
                <tr key={row.key} className="border-b border-border/60">
                  <td className="py-1.5 font-medium">
                    {row.label === '' ? t('cs.new.oneVariant') : row.label}
                  </td>
                  <td className="py-1.5 text-right">
                    <label className="sr-only" htmlFor={`price-${String(index)}`}>
                      {`${t('cs.col.price')} ${row.label}`}
                    </label>
                    <input
                      id={`price-${String(index)}`}
                      inputMode="decimal"
                      value={rowPrice[row.key] ?? ''}
                      placeholder={taka}
                      onChange={(event) =>
                        setRowPrice((current) => ({ ...current, [row.key]: event.target.value }))
                      }
                      className={`${control} w-28 text-right tabular-nums`}
                    />
                  </td>
                  {mayReceive ? (
                    <td className="py-1.5 text-right">
                      <label className="sr-only" htmlFor={`qty-${String(index)}`}>
                        {`${t('cs.col.openingQty')} ${row.label}`}
                      </label>
                      <input
                        id={`qty-${String(index)}`}
                        inputMode="numeric"
                        value={rowQty[row.key] ?? ''}
                        placeholder="0"
                        onChange={(event) =>
                          setRowQty((current) => ({ ...current, [row.key]: event.target.value }))
                        }
                        className={`${control} w-24 text-right tabular-nums`}
                      />
                    </td>
                  ) : null}
                </tr>
              ))}
            </tbody>
          </table>
          <p className="text-xs text-muted-foreground">{t('cs.new.gridHelp')}</p>
        </section>

        {wantsStock ? (
          <section aria-labelledby="stock-heading" className="space-y-3">
            <h2 id="stock-heading" className="text-sm font-semibold">
              {t('cs.new.openingStock')}
            </h2>
            <p className="text-sm text-muted-foreground">
              {t(mayPrice ? 'cs.new.openingHelp' : 'cs.receive.helpDraft')}
            </p>
            <div className="grid gap-3 sm:grid-cols-3">
              <Field label={t('cs.location')}>
                <select
                  value={chosenLocation}
                  onChange={(event) => setLocationId(event.target.value)}
                  className={control}
                >
                  {receivable.map((location) => (
                    <option key={location.id} value={location.id}>
                      {location.name}
                    </option>
                  ))}
                </select>
              </Field>
              <Field label={t('cs.supplier')}>
                <select
                  value={supplierId}
                  onChange={(event) => setSupplierId(event.target.value)}
                  className={control}
                >
                  <option value="">{t('cs.chooseSupplier')}</option>
                  {(suppliers.data?.items ?? []).map((supplier) => (
                    <option key={supplier.id} value={supplier.id}>
                      {supplier.name} ({supplier.code})
                    </option>
                  ))}
                </select>
              </Field>
              {mayPrice ? (
                <Field label={t('cs.costPerPiece')}>
                  <input
                    inputMode="decimal"
                    value={costTaka}
                    onChange={(event) => setCostTaka(event.target.value)}
                    className={`${control} text-right tabular-nums`}
                  />
                </Field>
              ) : null}
            </div>
            {(suppliers.data?.items ?? []).length === 0 && suppliers.isSuccess ? (
              <p className="text-sm text-muted-foreground">{t('cs.noSuppliers')}</p>
            ) : null}
            {mayPrice && costPoisha !== null ? (
              <p className="text-sm">
                {`${String(units)} ${t('cs.units')} · `}
                <Money poisha={(BigInt(costPoisha) * BigInt(units)).toString()} />
              </p>
            ) : null}
          </section>
        ) : null}

        <section aria-labelledby="photos-heading" className="space-y-3">
          <h2 id="photos-heading" className="text-sm font-semibold">
            {t('cs.photos.title')}
          </h2>
          <p className="text-sm text-muted-foreground">{t('cs.photos.optional')}</p>
          {photos.length > 0 ? (
            <ul className="space-y-1 text-sm">
              {photos.map((photo) => (
                <li key={photo.id} className="flex items-center gap-2">
                  <span className="truncate">{photo.originalName ?? photo.id.slice(0, 8)}</span>
                  <Button
                    size="sm"
                    variant="ghost"
                    onClick={() =>
                      setPhotos((current) => current.filter((entry) => entry.id !== photo.id))
                    }
                  >
                    {t('cs.photos.remove')}
                  </Button>
                </li>
              ))}
            </ul>
          ) : null}
          <PhotoUploader onUploaded={(file) => setPhotos((current) => [...current, file])} />
        </section>

        {save.error !== null ? (
          <p role="alert" className="text-sm text-destructive">
            {save.error instanceof ApiError ? save.error.message : t('cs.saveFailed')}
            {created !== null ? ` ${t('cs.new.createdButStock')}` : ''}
          </p>
        ) : null}

        <div className="flex flex-wrap items-center gap-2">
          <Button disabled={!ready || save.isPending} onClick={() => save.mutate()}>
            {created !== null ? t('cs.new.retry') : t('cs.new.create')}
          </Button>
          <Button
            variant="ghost"
            onClick={() =>
              void navigate({ to: '/catalog', search: { page: 1, pageSize: DEFAULT_PAGE_SIZE } })
            }
          >
            {t('cs.cancel')}
          </Button>
          {created !== null ? (
            <Link
              to="/catalog/$productId"
              params={{ productId: created.id }}
              className="text-sm underline underline-offset-4"
            >
              {t('cs.new.openCreated')}
            </Link>
          ) : null}
        </div>
      </div>
    </PermissionGate>
  );
}

function rank(kind: string): number {
  return kind === 'size' ? 0 : kind === 'colour' ? 1 : 2;
}

/** The created SKU carrying exactly this row's values. */
function skuFor(product: CatalogProduct, row: VariantRow): string | undefined {
  return product.skus.find(
    (sku) =>
      sku.attributes.length === row.valueIds.length &&
      row.valueIds.every((id) => sku.attributes.some((pair) => pair.valueId === id)),
  )?.id;
}
