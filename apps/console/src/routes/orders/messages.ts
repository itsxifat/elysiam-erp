export type OrdersMessageKey = (typeof ORDERS_KEYS)[number];

export const ordersMessages = sectionCatalogue(ORDERS_KEYS);
export const ordersEn = ordersMessages.en;

/**
 * The orders screens' lookup, closing over the locale from M05's provider so the shell's
 * language switch changes these strings too.
 *
 * Throws on a missing value although the key type is narrow, because the dynamic call sites
 * build keys from server enums and cast them — a status the server added and this file does
 * not know would otherwise render as nothing at all.
 */
export function useOrdersT(): (key: OrdersMessageKey) => string {
  const { locale } = useLocale();
  return (key) => {
    const value = (ordersMessages[locale] as Record<string, string | undefined>)[key];
    if (value === undefined) throw new Error(`No ${locale} message for "${key}".`);
    return value;
  };
}

/** A key built from a server value, checked rather than cast. */
export function isOrdersKey(key: string): key is OrdersMessageKey {
  return Object.hasOwn(ordersEn, key);
}
