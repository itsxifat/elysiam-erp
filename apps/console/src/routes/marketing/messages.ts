export type MarketingMessageKey = (typeof MARKETING_KEYS)[number];

export const marketingMessages = sectionCatalogue(MARKETING_KEYS);
export const marketingEn = marketingMessages.en;

/** The section's lookup, following the shell's language switch. */
export function useMarketingT(): (key: MarketingMessageKey) => string {
  const { locale } = useLocale();
  return (key) => {
    const value = (marketingMessages[locale] as Record<string, string | undefined>)[key];
    if (value === undefined) throw new Error(`No ${locale} message for "${key}".`);
    return value;
  };
}

/** A key built from a server value, checked rather than cast. */
export function isMarketingKey(key: string): key is MarketingMessageKey {
  return Object.hasOwn(marketingEn, key);
}
