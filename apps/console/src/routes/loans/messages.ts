export type LoansMessageKey = (typeof LOANS_KEYS)[number];

export const loansMessages = sectionCatalogue(LOANS_KEYS);

/** The section's own lookup: a loan screen that reaches for another section's string does not compile. */
export function useLoansT(): (key: LoansMessageKey) => string {
  const { locale } = useLocale();
  return (key) => loansMessages[locale][key];
}
