import { businessDateSchema, ledgerIdSchema, positivePoishaSchema } from '@elysium/contracts';
import { z } from 'zod';

/**
 * The accounts endpoints' request shapes (architecture §7, §23).
 *
 * These belong in `packages/contracts` by convention, and M04's generator turns
 * that package into the typed OpenAPI client. They live here for the same reason
 * `files.schemas.ts` does: `packages/contracts/src/index.ts` is edited
 * concurrently by other agents this session, and a second write to a barrel
 * silently discards the first. The INTEGRATION section of this milestone's report
 * hands the integrator the move; it is a file rename and a re-export.
 *
 * What they do get right is §23's money rule: **every amount is a decimal string
 * of integer poisha**, never a JSON number. `JSON.parse` turns a crore-scale
 * poisha value into a double and drops its last digits, and the failure is
 * invisible — the number still looks like money.
 */

/** A poisha string that may be zero: a bank charge, a counted-empty till. */
export const nonNegativePoishaSchema = z
  .string()
  .max(16, 'Amounts are integer poisha, sent as a decimal string.')
  .regex(/^(0|[1-9]\d*)$/, 'Amounts are non-negative integer poisha, sent as a decimal string.')
  .refine(
    (value) => !/^\d+$/.test(value) || BigInt(value) <= 9_000_000_000_000_000n,
    'That amount is out of range.',
  );

/**
 * Register a wallet: name a `wallet_*` ledger account, or create one.
 *
 * Two shapes, because both are real. A brand's seeded chart already has Bank and
 * bKash and a hand-cash account per branch (D-084), so registering those is
 * naming an account that exists. A second bank account or a Nagad wallet has no
 * account yet, so `account.create` asks for one — a code, a name and a subtype,
 * and nothing else: an account's class, normal balance and party type follow from
 * its subtype and are never a client's to choose.
 */
export const createWalletSchema = z.object({
  account: z.union([
    z.object({ existingAccountId: z.string().uuid() }).strict(),
    z
      .object({
        code: z
          .string()
          .trim()
          .regex(/^[0-9A-Z][0-9A-Z-]{0,31}$/, 'An account code is digits, capitals and dashes.'),
        name: z.string().trim().min(1).max(120),
        subtype: z.enum(['wallet_cash', 'wallet_bank', 'wallet_bkash', 'wallet_mfs_other']),
      })
      .strict(),
  ]),
  /** Required for `wallet_cash`: hand cash is kept per branch (§7). */
  branchId: z.string().uuid().optional(),
  provider: z.string().trim().min(1).max(80).optional(),
  /**
   * The last digits of the account or wallet number.
   *
   * Bounded to four characters, and that is the masking: a field that accepts a
   * full bank account number will receive one, and it would then be in every
   * backup and every CSV export of this table (invariant 10, §25).
   */
  accountRefLast4: z
    .string()
    .trim()
    .regex(/^\d{2,4}$/, 'Give only the last two to four digits.')
    .optional(),
  requiresDailyClosing: z.boolean().default(true),
});
export type CreateWalletInput = z.infer<typeof createWalletSchema>;

export const updateWalletSchema = z
  .object({
    provider: z.string().trim().min(1).max(80).nullable().optional(),
    requiresDailyClosing: z.boolean().optional(),
    isActive: z.boolean().optional(),
  })
  .strict()
  .refine((value) => Object.keys(value).length > 0, 'Nothing to change.');
export type UpdateWalletInput = z.infer<typeof updateWalletSchema>;

/**
 * One cash entry.
 *
 * `entryId` is generated by the client, once per entry, and it is what makes a
 * double-clicked Save post one journal instead of two: it becomes the posting
 * rule's idempotency key (§7).
 *
 * `receiptFileId` is required for `petty_cash` and the schema says so, but it is
 * not the enforcement — the column has a CHECK and the service refuses before
 * either (check 2). A required field in a Zod schema is a convenience for the
 * client; it is not a property of the data.
 */
export const cashEntrySchema = z
  .object({
    entryId: z.string().uuid(),
    walletId: z.string().uuid(),
    kind: z.enum(['cash_in', 'cash_out', 'petty_cash']),
    categoryAccountId: z.string().uuid(),
    amountPoisha: positivePoishaSchema,
    receiptFileId: z.string().uuid().optional(),
    memo: z.string().trim().max(500).optional(),
  })
  .strict()
  .refine((value) => value.kind !== 'petty_cash' || value.receiptFileId !== undefined, {
    message: 'Petty cash needs a receipt photo.',
    path: ['receiptFileId'],
  });
export type CashEntryInput = z.infer<typeof cashEntrySchema>;

/** A transfer between two of the org's own wallets (§7: Dr W2 + Dr charges / Cr W1). */
export const walletTransferSchema = z
  .object({
    transferId: z.string().uuid(),
    fromWalletId: z.string().uuid(),
    toWalletId: z.string().uuid(),
    amountPoisha: positivePoishaSchema,
    /** Default zero. Non-zero needs `chargeAccountId`, which must be `bank_charges`. */
    chargePoisha: nonNegativePoishaSchema.default('0'),
    chargeAccountId: z.string().uuid().optional(),
    memo: z.string().trim().max(500).optional(),
  })
  .strict()
  .refine((value) => value.fromWalletId !== value.toWalletId, {
    message: 'Pick two different wallets.',
    path: ['toWalletId'],
  })
  .refine((value) => BigInt(value.chargePoisha) > 0n === (value.chargeAccountId !== undefined), {
    message: 'A charge needs a bank-charges account, and an account needs a charge.',
    path: ['chargeAccountId'],
  });
export type WalletTransferInput = z.infer<typeof walletTransferSchema>;

/**
 * A daily closing: the counted cash in one wallet on one business date.
 *
 * The expected balance is **not** in the body. It is derived from the ledger at
 * the moment of the count, and a client-supplied expectation would let a
 * variance be made to disappear by sending the number that makes it zero.
 */
export const closeWalletSchema = z
  .object({
    closingId: z.string().uuid(),
    walletId: z.string().uuid(),
    businessDate: businessDateSchema,
    countedPoisha: nonNegativePoishaSchema,
    memo: z.string().trim().max(500).optional(),
  })
  .strict();
export type CloseWalletInput = z.infer<typeof closeWalletSchema>;

export const walletIdParamSchema = ledgerIdSchema;

/** A report over a range of business dates, optionally one branch. */
export const reportRangeSchema = z
  .object({
    from: businessDateSchema,
    to: businessDateSchema,
    branchId: z.string().uuid().optional(),
  })
  .refine((value) => value.from <= value.to, {
    message: '`from` must not be after `to`.',
    path: ['from'],
  });

export const asOfSchema = z.object({
  asOf: businessDateSchema,
  branchId: z.string().uuid().optional(),
});

/**
 * The wallet list. Closed wallets are left out unless asked for: the cash
 * screens have nothing to do with them, and the setup screen needs them to
 * reopen one.
 */
export const walletListQuerySchema = z.object({
  asOf: businessDateSchema.optional(),
  includeInactive: z
    .enum(['true', 'false'])
    .optional()
    .transform((value) => value === 'true'),
});

/** Payables and receivables aging, as of a business date. */
export const agingQuerySchema = z.object({
  asOf: businessDateSchema,
  side: z.enum(['payable', 'receivable']).default('payable'),
});

export const cashEntryListSchema = z.object({
  from: businessDateSchema.optional(),
  to: businessDateSchema,
  walletId: z.string().uuid().optional(),
  status: z.enum(['pending_approval', 'posted', 'rejected']).optional(),
});
