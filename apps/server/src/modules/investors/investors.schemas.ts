import { businessDateSchema, ledgerIdSchema, positivePoishaSchema } from '@elysium/contracts';
import { z } from 'zod';

/**
 * The investor endpoints' request shapes (architecture §15, §23).
 *
 * These belong in `packages/contracts` by convention, and M04's generator turns
 * that package into the typed OpenAPI client. They live here for the same reason
 * `wallets.schemas.ts` and `files.schemas.ts` do: `packages/contracts/src/index.ts`
 * is edited concurrently by other agents this session, and a second write to a
 * barrel silently discards the first. The INTEGRATION section of this milestone's
 * report hands the integrator the move; it is a file rename and a re-export.
 *
 * What they do get right is §23's money rule: **every amount is a decimal string
 * of integer poisha**, never a JSON number. `JSON.parse` turns a crore-scale
 * poisha value into a double and drops its last digits, and an investor's capital
 * is exactly the figure that reaches crore scale.
 */

/** `YYYY-MM`, the period a distribution is declared for. */
const monthSchema = z.string().regex(/^\d{4}-(0[1-9]|1[0-2])$/, 'A period is a month, as YYYY-MM.');

/**
 * A phone number as a person types it. Masked before it is stored, never after
 * (invariant 10): what reaches the column is `+8801XXXXX678`.
 */
const phoneSchema = z
  .string()
  .trim()
  .min(6, 'That does not look like a phone number.')
  .max(20, 'That does not look like a phone number.');

export const createInvestorSchema = z
  .object({
    /** A short human reference, unique per org: `INV-01`. */
    code: z
      .string()
      .trim()
      .regex(/^[0-9A-Za-z][0-9A-Za-z-]{0,31}$/, 'A code is letters, digits and dashes.'),
    name: z.string().trim().min(1).max(160),
    /**
     * The portal login this investor reads their own rows through.
     *
     * Optional, because an investor is often recorded before they have an
     * account. It is checked against an `investor` membership of this org before
     * it is stored: an unchecked user id here would hand somebody else's capital
     * and KYC to whoever it named, which is the whole of check 1.
     */
    userId: z.string().trim().min(1).max(64).optional(),
    phone: phoneSchema.optional(),
    email: z.string().trim().email().max(200).optional(),
    /**
     * The agreed profit share, in basis points (1250 = 12.5%).
     *
     * Basis points rather than a decimal percentage, for the same reason money is
     * poisha: 12.5% is exact as an integer and inexact as a float.
     */
    shareBps: z.number().int().min(0).max(10_000).default(0),
    joinedOn: businessDateSchema,
    notes: z.string().trim().max(2_000).optional(),
  })
  .strict();
export type CreateInvestorInput = z.infer<typeof createInvestorSchema>;

export const updateInvestorSchema = z
  .object({
    name: z.string().trim().min(1).max(160).optional(),
    userId: z.string().trim().min(1).max(64).optional(),
    phone: phoneSchema.nullable().optional(),
    email: z.string().trim().email().max(200).nullable().optional(),
    shareBps: z.number().int().min(0).max(10_000).optional(),
    notes: z.string().trim().max(2_000).nullable().optional(),
    /**
     * Only ever `exited`. An investor who has exited is not reinstated — a
     * trigger in 0060 refuses it — because the settlement that ended their
     * position is a fact, and a second one would need its own row and its own
     * journals.
     */
    status: z.literal('exited').optional(),
  })
  .strict()
  .refine((value) => Object.keys(value).length > 0, 'Nothing to change.');
export type UpdateInvestorInput = z.infer<typeof updateInvestorSchema>;

/**
 * One capital contribution.
 *
 * `investmentId` is generated by the client, once per contribution, and it is what
 * makes a double-clicked Save post one journal instead of two: it becomes the
 * posting rule's idempotency key (§7).
 */
export const recordInvestmentSchema = z
  .object({
    investmentId: z.string().uuid(),
    investorId: z.string().uuid(),
    /** The `wallet_*` ledger account the money arrived in. */
    walletAccountId: z.string().uuid(),
    amountPoisha: positivePoishaSchema,
    /** The date this lot's lock-in ends, if it has one (§15). */
    lockInUntil: businessDateSchema.optional(),
    terms: z.string().trim().max(2_000).optional(),
    memo: z.string().trim().max(500).optional(),
  })
  .strict();
export type RecordInvestmentInput = z.infer<typeof recordInvestmentSchema>;

/**
 * A profit distribution declared for one month (D-019).
 *
 * The **amount is typed by a person** — D-019 defines no formula — and the split
 * across investors is computed by the server from the basis. A client-supplied
 * split is deliberately not accepted: the parts have to sum to the total exactly
 * or the journal cannot post, and "the client did the arithmetic" is not a
 * property anybody can verify later.
 *
 * `investorIds` narrows the participants — an investor who joined after the period
 * ended should not share in it — and defaults to every active investor.
 */
export const declareDistributionSchema = z
  .object({
    distributionId: z.string().uuid(),
    /** The month the profit was earned in, as `YYYY-MM`. */
    month: monthSchema,
    totalPoisha: positivePoishaSchema,
    basis: z.enum(['share_bps', 'capital']).default('share_bps'),
    investorIds: z.array(z.string().uuid()).min(1).max(200).optional(),
    memo: z.string().trim().max(500).optional(),
  })
  .strict();
export type DeclareDistributionInput = z.infer<typeof declareDistributionSchema>;

/** A withdrawal request: `capital` draws on equity, `profit` on declared profit. */
export const requestWithdrawalSchema = z
  .object({
    withdrawalId: z.string().uuid(),
    investorId: z.string().uuid(),
    kind: z.enum(['capital', 'profit']),
    amountPoisha: positivePoishaSchema,
    reason: z.string().trim().max(500).optional(),
  })
  .strict();
export type RequestWithdrawalInput = z.infer<typeof requestWithdrawalSchema>;

/**
 * Reviewing a withdrawal: confirm the position covers it and name the account it
 * would be paid from.
 *
 * The account is chosen here, before a checker is asked, because "approve this
 * payment" is not answerable without knowing where the money leaves from. There is
 * no amount in this body — the amount is the investor's request and it is frozen
 * (0060); a reviewer who disagrees rejects it and a new request is raised.
 */
export const reviewWithdrawalSchema = z
  .object({
    walletAccountId: z.string().uuid(),
    note: z.string().trim().max(500).optional(),
  })
  .strict();
export type ReviewWithdrawalInput = z.infer<typeof reviewWithdrawalSchema>;

/** A private document about an investor (§22, check 3). */
export const attachDocumentSchema = z
  .object({
    investorId: z.string().uuid(),
    investmentId: z.string().uuid().optional(),
    kind: z.enum(['kyc', 'agreement', 'other']),
    title: z.string().trim().min(1).max(200),
    /**
     * A `files.objects` id, already uploaded with the `investor-document` purpose
     * and `private` visibility. The service refuses anything else — a KYC scan
     * uploaded as a product image would be readable by everyone with
     * `read Catalog`, which is everyone.
     */
    fileId: z.string().uuid(),
  })
  .strict();
export type AttachDocumentInput = z.infer<typeof attachDocumentSchema>;

/**
 * Closing a withdrawal or a declaration that will not go ahead.
 *
 * A reason rather than nothing, because this is the one transition with no journal
 * and no approval behind it: the audit row is the whole record of why an investor's
 * request was refused, and "rejected, no reason given" is the row somebody reads a
 * year later.
 */
export const rejectSchema = z
  .object({ reason: z.string().trim().min(1).max(500).optional() })
  .strict();
export type RejectInput = z.infer<typeof rejectSchema>;

export const investorIdParamSchema = ledgerIdSchema;

/** A statement over a range of business dates (§15). */
export const statementQuerySchema = z
  .object({
    from: businessDateSchema,
    to: businessDateSchema,
  })
  .refine((value) => value.from <= value.to, {
    message: '`from` must not be after `to`.',
    path: ['from'],
  });
export type StatementQuery = z.infer<typeof statementQuerySchema>;

export const investorListQuerySchema = z
  .object({
    includeExited: z
      .enum(['true', 'false'])
      .default('false')
      .transform((value) => value === 'true'),
  })
  .partial({ includeExited: true });

export const withdrawalListQuerySchema = z.object({
  investorId: z.string().uuid().optional(),
  status: z.enum(['requested', 'reviewed', 'approved', 'paid', 'rejected']).optional(),
});
