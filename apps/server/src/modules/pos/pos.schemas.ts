import {
  businessDateSchema,
  nonNegativePoishaSchema,
  posSyncSchema,
  returnDocumentSchema,
  saleDocumentSchema,
  type PosSyncInput,
  type ReturnDocument,
  type SaleDocument,
} from '@elysium/contracts';
import { z } from 'zod';

/**
 * The POS's wire shapes (architecture §23), validated at the edge.
 *
 * The till documents and the sync body are in `packages/contracts` (`pos.ts`),
 * shared with the till itself and its offline test double; what is here is the
 * staff side — registers, shifts, reviews, closings — which only the server and
 * the console read. Every amount is integer poisha as a decimal string (invariant 1).
 */

export {
  nonNegativePoishaSchema,
  returnDocumentSchema,
  saleDocumentSchema,
  type ReturnDocument,
  type SaleDocument,
};
export const syncSchema = posSyncSchema;
export type SyncInput = PosSyncInput;

const uuid = z.string().uuid();

export const createRegisterSchema = z
  .object({
    branchId: uuid,
    locationId: uuid,
    code: z.string().regex(/^[A-Z0-9]{2,8}$/, 'A register code is 2 to 8 capitals or digits.'),
    name: z.string().trim().min(1).max(80),
    cashWalletId: uuid,
    bkashWalletId: uuid.nullable().optional(),
    cardWalletId: uuid.nullable().optional(),
  })
  .strict();
export type CreateRegisterInput = z.infer<typeof createRegisterSchema>;

export const updateRegisterSchema = z
  .object({
    name: z.string().trim().min(1).max(80).optional(),
    isActive: z.boolean().optional(),
    bkashWalletId: uuid.nullable().optional(),
    cardWalletId: uuid.nullable().optional(),
  })
  .strict();
export type UpdateRegisterInput = z.infer<typeof updateRegisterSchema>;

export const openShiftSchema = z
  .object({
    /** Generated by the till, so a retried open over a flaky link opens one shift. */
    shiftId: uuid,
    registerId: uuid,
    openingFloatPoisha: nonNegativePoishaSchema,
  })
  .strict();
export type OpenShiftInput = z.infer<typeof openShiftSchema>;

export const closeShiftSchema = z
  .object({
    countedCashPoisha: nonNegativePoishaSchema,
    note: z.string().trim().max(500).optional(),
  })
  .strict();
export type CloseShiftInput = z.infer<typeof closeShiftSchema>;

export const resolveReviewSchema = z
  .object({
    action: z.enum(['post', 'void']),
    note: z.string().trim().min(1).max(500),
  })
  .strict();
export type ResolveReviewInput = z.infer<typeof resolveReviewSchema>;

export const reviewListSchema = z
  .object({
    branchId: uuid.optional(),
    status: z.enum(['open', 'posted', 'voided']).optional(),
  })
  .strict();

export const shiftListSchema = z
  .object({
    branchId: uuid.optional(),
    registerId: uuid.optional(),
    status: z.enum(['open', 'closed']).optional(),
    from: businessDateSchema.optional(),
    to: businessDateSchema.optional(),
  })
  .strict();

export const catalogPageSchema = z
  .object({
    after: z.string().max(64).optional(),
    limit: z.coerce.number().int().min(1).max(500).default(500),
  })
  .strict();

export const rangeSchema = z
  .object({ from: businessDateSchema, to: businessDateSchema })
  .strict()
  .refine((value) => value.from <= value.to, { message: '`from` must not be after `to`.' });

export const dateSchema = z.object({ date: businessDateSchema.optional() }).strict();

export const branchClosingSchema = z
  .object({
    closingId: uuid,
    businessDate: businessDateSchema,
    counts: z
      .array(z.object({ walletId: uuid, countedPoisha: nonNegativePoishaSchema }).strict())
      .min(1)
      .max(10),
    note: z.string().trim().max(500).optional(),
  })
  .strict();
export type BranchClosingInput = z.infer<typeof branchClosingSchema>;

export const promoCheckSchema = z
  .object({
    registerId: uuid,
    code: z.string().trim().min(1).max(40),
    basketPoisha: nonNegativePoishaSchema,
  })
  .strict();

export const idParamSchema = uuid;
