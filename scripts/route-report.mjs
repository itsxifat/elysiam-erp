#!/usr/bin/env node
/**
 * The route report (M30 check 3).
 *
 * `pnpm check:routes` proves, on every commit, that each route declares what it needs and
 * that each non-public route is driven by the route-matrix suite as every role. That gate
 * prints a pass or a list of failures; launch readiness also wants the list itself, so a
 * reviewer can read every route with its ability and the tests that exercise it.
 *
 * It boots the built application exactly as the gate does (`inspectApplication`), so the two
 * cannot disagree about which routes exist, then reads the test sources for:
 *
 * * the **matrix fixture**: the file that holds the route's `'METHOD /path'` entry, which
 *   `route-matrix.e2e.test.ts` drives as every role;
 * * the **feature tests**: test files with a request path matching the route's (`:id`
 *   segments match any one segment, so `${id}` in a template literal counts).
 *
 * Usage (after `pnpm --filter @elysium/server build`):
 *   pnpm report:routes                 writes docs/review/M30/route-report.md
 *   pnpm report:routes -- <out.md>     writes somewhere else
 */

import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath, pathToFileURL } from 'node:url';

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DEFAULT_OUT = path.join(REPO_ROOT, 'docs', 'review', 'M30', 'route-report.md');

/** Where tests live. The console's and portal's browser specs call the API too. */
const TEST_ROOTS = ['apps/server/src', 'apps/console/e2e', 'apps/portal/e2e', 'apps/pos/e2e'];
const TEST_FILE = /\.(test|stack|spec)\.ts$/;
const FIXTURE_FILE = /(route-fixtures\.ts|route-matrix\.e2e\.test\.ts)$/;

function walk(directory) {
  const found = [];
  let entries;
  try {
    entries = readdirSync(directory, { withFileTypes: true });
  } catch {
    return found;
  }
  for (const entry of entries) {
    if (entry.name === 'node_modules' || entry.name === 'dist') continue;
    const full = path.join(directory, entry.name);
    if (entry.isDirectory()) found.push(...walk(full));
    else found.push(full);
  }
  return found;
}

function escapeRegExp(text) {
  return text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/**
 * A regular expression for a route's path as test code spells a request to it.
 *
 * `:param` matches one path segment however it is written (`${id}`, a literal uuid), and the
 * path must end there — at a quote, a query string or whitespace — so `/v1/orders` does not
 * also claim every test of `/v1/orders/:id/confirm`.
 */
export function pathPattern(routePath) {
  const body = routePath
    .split('/')
    .map((segment) => (segment.startsWith(':') ? '[^/\'"`?\\s]+' : escapeRegExp(segment)))
    .join('/');
  return new RegExp(`${body}(?=['"\`?\\s]|$)`);
}

/** The pure part: routes plus test sources in, markdown out. Tested without a boot. */
export function renderReport({
  routes,
  manifest,
  routeKey,
  sources,
  generatedAt,
  commit,
  controllerFiles = new Map(),
}) {
  const fixtures = sources.filter((source) => FIXTURE_FILE.test(source.file));
  const tests = sources.filter(
    (source) => TEST_FILE.test(source.file) && !FIXTURE_FILE.test(source.file),
  );

  const rows = routes.map((route) => {
    const key = routeKey(route);
    const quoted = `'${key}'`;
    const fixture = fixtures.find((source) => source.text.includes(quoted));
    const pattern = pathPattern(route.path);
    const covering = tests.filter((source) => pattern.test(source.text)).map((s) => s.file);
    return {
      key,
      route,
      declared: route.declared ?? (route.problem === null ? 'MISSING' : 'CONTRADICTORY'),
      matrix: manifest.includes(key),
      fixture: fixture?.file ?? null,
      covering,
    };
  });

  const isPublic = (row) => row.declared.startsWith('public:');
  const publicRows = rows.filter(isPublic);
  const matrixRows = rows.filter((row) => row.matrix);
  const undeclared = rows.filter(
    (row) => row.declared === 'MISSING' || row.declared === 'CONTRADICTORY',
  );
  const untested = rows.filter((row) => !isPublic(row) && !row.matrix);
  const noFeatureTest = rows.filter((row) => row.covering.length === 0);
  const publicWithoutTest = publicRows.filter((row) => row.covering.length === 0);

  const cell = (text) => String(text).replaceAll('|', '\\|');
  const short = (file) => path.basename(file);

  const lines = [
    '# Route report',
    '',
    `Generated by \`pnpm report:routes\` on ${generatedAt} at commit \`${commit}\` (M30 check 3).`,
    'Read from the built application the way `pnpm check:routes` reads it, so the two list the same routes.',
    '',
    '## Summary',
    '',
    `| What | Count |`,
    `| --- | --- |`,
    `| Routes | ${String(rows.length)} |`,
    `| Declaring an ability (\`action:Subject\`) | ${String(rows.filter((r) => r.route.ability !== null).length)} |`,
    `| \`@AuthenticatedOnly\` | ${String(rows.filter((r) => r.declared === 'authenticated').length)} |`,
    `| \`@Public\` | ${String(publicRows.length)} |`,
    `| Driven as every role by the route-matrix suite | ${String(matrixRows.length)} |`,
    `| Undeclared or contradictory | ${String(undeclared.length)} |`,
    `| Non-public and missing from the matrix | ${String(untested.length)} |`,
    `| With no HTTP feature test (matrix suite and module suites only) | ${String(noFeatureTest.length)} |`,
    `| Public with no test matching its path | ${String(publicWithoutTest.length)} |`,
    '',
    'How to read it:',
    '',
    '- **Declared** is what the guard enforces: `action:Subject` is a CASL ability (§6), `authenticated` needs a session and no subject, `public:<reason>` is open on purpose.',
    "- **Matrix fixture** is the file holding the route's fixture; `route-matrix.e2e.test.ts` calls it as every role and asserts the guard admits exactly the roles the permission matrix grants, and that a successful mutation leaves an audit row.",
    '- **Feature tests** are the test files whose request paths match the route. A route with none is still covered by the matrix suite for its permissions, but not for its behaviour beyond the guard.',
    '',
    '## Routes',
    '',
    '| Method | Path | Declared | Matrix fixture | Feature tests |',
    '| --- | --- | --- | --- | --- |',
  ];

  for (const row of rows) {
    const fixture = row.matrix ? (row.fixture === null ? 'manifest' : short(row.fixture)) : '—';
    const covering =
      row.covering.length === 0 ? '—' : row.covering.map((file) => short(file)).join(', ');
    lines.push(
      `| ${row.route.method} | \`${cell(row.route.path)}\` | ${cell(row.declared)} | ${cell(fixture)} | ${cell(covering)} |`,
    );
  }

  if (noFeatureTest.length > 0) {
    lines.push(
      '',
      '## Routes with no HTTP feature test',
      '',
      'Their permissions are tested for every role by the matrix suite, and no other test file',
      'calls their path over HTTP. The module suites beside the controller test the service',
      'behind them directly (listed where the module has any).',
      '',
    );
    for (const row of noFeatureTest) {
      const file = controllerFiles.get(row.route.controller);
      const directory = file === undefined ? null : path.posix.dirname(file);
      const suites =
        directory === null
          ? []
          : sources
              .filter(
                (source) =>
                  path.posix.dirname(source.file) === directory &&
                  TEST_FILE.test(source.file) &&
                  !FIXTURE_FILE.test(source.file),
              )
              .map((source) => short(source.file));
      lines.push(
        `- \`${row.key}\` (${row.declared})${suites.length === 0 ? '' : `: ${suites.join(', ')}`}`,
      );
    }
  }

  lines.push('');
  return {
    markdown: lines.join('\n'),
    counts: {
      routes: rows.length,
      public: publicRows.length,
      matrix: matrixRows.length,
      undeclared: undeclared.length,
      untested: untested.length,
      noFeatureTest: noFeatureTest.length,
    },
  };
}

/** Controller class → its source file, so a route can be traced to its module's suites. */
function readControllerFiles() {
  const map = new Map();
  for (const file of walk(path.join(REPO_ROOT, 'apps/server/src'))) {
    if (!file.endsWith('.controller.ts')) continue;
    const text = readFileSync(file, 'utf8');
    for (const match of text.matchAll(/export class (\w+)/g)) {
      map.set(match[1], path.relative(REPO_ROOT, file).replaceAll('\\', '/'));
    }
  }
  return map;
}

function readSources() {
  const sources = [];
  for (const root of TEST_ROOTS) {
    for (const file of walk(path.join(REPO_ROOT, root))) {
      if (!TEST_FILE.test(file) && !FIXTURE_FILE.test(file)) continue;
      sources.push({
        file: path.relative(REPO_ROOT, file).replaceAll('\\', '/'),
        text: readFileSync(file, 'utf8'),
      });
    }
  }
  return sources;
}

async function main() {
  const out = process.argv[2] === undefined ? DEFAULT_OUT : path.resolve(process.argv[2]);
  const { inspectApplication } = await import(
    pathToFileURL(path.join(REPO_ROOT, 'scripts', 'check-route-matrix.mjs')).href
  );
  const { routes, manifest, routeKey } = await inspectApplication();

  const { execFileSync } = await import('node:child_process');
  let commit = 'unknown';
  try {
    commit = execFileSync('git', ['rev-parse', '--short', 'HEAD'], {
      cwd: REPO_ROOT,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
  } catch {
    // No git metadata: the report still stands.
  }

  const { markdown, counts } = renderReport({
    routes,
    manifest,
    routeKey,
    sources: readSources(),
    generatedAt: new Date().toISOString().slice(0, 10),
    commit,
    controllerFiles: readControllerFiles(),
  });
  mkdirSync(path.dirname(out), { recursive: true });
  writeFileSync(out, markdown, 'utf8');
  console.log(
    `route-report: ${String(counts.routes)} routes (${String(counts.public)} public, ` +
      `${String(counts.matrix)} matrix-tested, ${String(counts.noFeatureTest)} without an HTTP feature test) → ` +
      path.relative(REPO_ROOT, out),
  );
  if (counts.undeclared > 0 || counts.untested > 0) {
    console.error('route-report: some routes fail the gate; run `pnpm check:routes`.');
    process.exit(1);
  }
}

const invokedDirectly =
  process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href;

if (invokedDirectly) {
  main().catch((error) => {
    console.error('route-report: failed.');
    console.error(error);
    process.exit(1);
  });
}
