import { sql } from 'drizzle-orm';
import {
  bigint,
  check,
  index,
  jsonb,
  pgSchema,
  text,
  timestamp,
  unique,
  uuid,
} from 'drizzle-orm/pg-core';

import { organizations } from '../org/index.js';
import { users } from '../iam/index.js';
import { primaryId, timestamps } from '../columns.js';

/**
 * Stored objects (architecture §22).
 *
 * The bytes live in R2 or on disk; this table is the only record of what they
 * are, whose they are and who may see them. Two consequences follow from that
 * and shape every column below.
 *
 * **The row is the authorization, not the key.** §22 says a private object is
 * served "only through short-lived signed URLs after an authorization check",
 * and the check needs something to check against. A signed URL is a bearer
 * token: once issued it works for anyone holding it, so the decision has to
 * happen before it is signed and it has to happen against facts kept here —
 * `visibility`, `owner_user_id`, `org_id`. Storing only the key and inferring
 * the rest from the path would make the permission a property of a string an
 * attacker can guess at.
 *
 * **Tenant table, with the full treatment.** A file is somebody's KYC scan or
 * somebody's payslip. `org_id NOT NULL`, RLS ENABLE and FORCE, and the policy
 * generated by `tenantTableSql()` — invariant 4, and here the invariant is
 * doing visible work: without it a uuid from another brand's URL would resolve.
 */
export const files = pgSchema('files');

/**
 * Which bucket the object belongs in (§22).
 *
 * `private` is the default everywhere it is not stated, and the column is
 * `not null` with that default so the safe value is what a forgotten field
 * produces. A mistake that makes a payslip public is not recoverable by
 * changing the column later — it has already been fetched and cached.
 */
export const fileVisibility = files.enum('file_visibility', ['private', 'public']);

/**
 * Where an object is in its life.
 *
 * `pending` is a row created when the upload ticket was issued, before the
 * bytes exist. It has to exist first: the key is derived from the row's id, and
 * the id has to be allocated before anything can be signed for it.
 *
 * `stored` means the bytes have been seen by the server — size, sha256 and the
 * sniffed type all recorded. Nothing downloads a `pending` row, so an
 * abandoned upload is inert rather than a hole.
 */
export const fileStatus = files.enum('file_status', ['pending', 'stored']);

export const fileObjects = files.table(
  'objects',
  {
    id: primaryId,

    orgId: uuid('org_id')
      .notNull()
      .references(() => organizations.id, { onDelete: 'restrict' }),

    /**
     * The key in the storage bucket, exactly as the driver will be given it.
     *
     * Globally unique because it embeds this row's own uuid. Recorded rather
     * than recomputed, so a later change to the key scheme cannot orphan every
     * object written under the old one.
     */
    storageKey: text('storage_key').notNull(),

    /**
     * `local` or `r2`.
     *
     * On the row, not read from configuration at download time. A staging
     * database restored into development would otherwise ask the local driver
     * for keys that only exist in R2, and the failure — "not found" for a file
     * that plainly exists — sends whoever hits it looking in the wrong place.
     */
    driver: text('driver').notNull(),

    visibility: fileVisibility('visibility').notNull().default('private'),
    status: fileStatus('status').notNull().default('pending'),

    /**
     * What this file is *for*: `kyc`, `invoice`, `payslip`, `product-image`,
     * `courier-proof`.
     *
     * Not decoration, and not a MIME type. The download check asks "may this
     * caller see this kind of thing", and a `mime` of `application/pdf` cannot
     * answer it — a supplier invoice and a staff payslip are the same MIME
     * type and very different questions. Free text rather than an enum because
     * every later milestone adds one, and a migration per purpose would make
     * adding a document type a database change.
     */
    purpose: text('purpose').notNull(),

    /**
     * The person who uploaded it.
     *
     * Not an org-scoped reference, because `iam.users` is global (§5 exception
     * 4): the same person works for three brands. Nullable for objects the
     * server produces — a rendered invoice has an org but no uploader, and
     * writing the requesting user there would claim they authored it.
     */
    ownerUserId: text('owner_user_id').references(() => users.id, { onDelete: 'set null' }),

    /** What the server decided the bytes are, after sniffing them on ingest. */
    mime: text('mime').notNull(),

    /**
     * Size in bytes.
     *
     * `bigint` rather than `integer` — not for money reasons (invariant 1 is
     * about poisha and this is not money) but because `integer` caps at 2 GiB
     * and a column that silently cannot represent a value is a worse problem
     * than eight extra bytes. Null while the row is `pending`: nothing has been
     * measured yet, and a `0` would read as an empty file.
     */
    sizeBytes: bigint('size_bytes', { mode: 'bigint' }),

    /**
     * SHA-256 of the stored bytes, lowercase hex.
     *
     * §22 asks for it, and it earns its place three ways: it proves the bytes
     * that arrived are the bytes that were signed for, it lets a re-upload of
     * the same document be recognised instead of duplicated, and it is what a
     * dispute about an altered invoice is settled with. Null while `pending`.
     */
    sha256: text('sha256'),

    /** The name the uploader's machine used. Shown to people; never a key. */
    originalName: text('original_name'),

    /**
     * Derived image variants: `{ thumb: {key, width, height}, … }`.
     *
     * Kept as one document rather than a child table because they are written
     * once, together, by the image job, and read together. A child table would
     * buy referential integrity over rows nothing else ever references.
     */
    variants: jsonb('variants').notNull().default({}),

    /**
     * When the image job finished, or null if it has not run or was not
     * applicable. Distinguishes "no variants because it is a PDF" from "no
     * variants because the job has not run yet", which matters to a UI deciding
     * whether to show a spinner or the original.
     */
    processedAt: timestamp('processed_at', { withTimezone: true, mode: 'date' }),

    ...timestamps,
  },
  (table) => [
    index('file_objects_org_idx').on(table.orgId),

    /*
     * The target of every later reference to a file — a product image, a
     * payslip PDF, a courier proof-of-delivery. It carries org_id so those
     * references can be composite foreign keys and cannot be satisfied from
     * another org's rows (D-047). Declared now, with the table, because adding
     * it later means a migration that can fail on data that already violates it.
     */
    unique('file_objects_org_id_id_key').on(table.orgId, table.id),

    unique('file_objects_storage_key_key').on(table.storageKey),

    /*
     * Deduplication and tamper questions are both "find the rows with this
     * hash, in this org". Org first because every query has it and a
     * hash-first index would make the common lookup scan other brands' rows
     * before filtering them out.
     */
    index('file_objects_org_sha256_idx').on(table.orgId, table.sha256),

    /* The image job's queue: rows that are stored but not yet processed. */
    index('file_objects_org_purpose_idx').on(table.orgId, table.purpose),

    /*
     * A storage key must contain the row's own id.
     *
     * Not cosmetic. The download path authorizes the *row* and then signs the
     * *key*, so if the two could disagree, a caller with permission on their
     * own file could be handed a URL for somebody else's object simply by
     * writing that object's key onto their own row. Tying the key to the id
     * closes that by construction rather than by every writer remembering.
     *
     * A containment check rather than an exact string because the month
     * segment and the extension are derived when the ticket is issued; the id
     * is the part that has to match.
     */
    check(
      'file_objects_key_matches_id',
      sql`position(${table.id}::text in ${table.storageKey}) > 0`,
    ),

    /*
     * A private object's key lives under `private/`, a public one under
     * `public/`.
     *
     * The prefix is what a CDN origin rule and a bucket lifecycle policy are
     * written against, so a row whose visibility and prefix disagree is an
     * object the CDN would serve while the database calls it private. That is
     * the exact shape of an accidental payslip leak, and it is cheap to make
     * impossible.
     */
    check(
      'file_objects_visibility_matches_prefix',
      sql`(${table.visibility} = 'private' and ${table.storageKey} like 'private/%')
       or (${table.visibility} = 'public' and ${table.storageKey} like 'public/%')`,
    ),

    /** Only the two drivers that exist. */
    check('file_objects_driver_known', sql`${table.driver} in ('local', 'r2')`),

    /*
     * A stored row has been measured; a pending one has not.
     *
     * Without this, `pending` is a label rather than a state: a row could
     * claim `stored` with no sha256, and the download path would hand out a
     * URL for bytes nobody has ever verified. The size ceiling is here too,
     * because a negative or absurd value can only come from a bug and is
     * better refused at the boundary than reasoned about downstream. 100 MiB
     * is comfortably above the largest per-type limit in `ALLOWED_MIME_TYPES`
     * and is the structural backstop, not the policy.
     */
    check(
      'file_objects_stored_is_complete',
      sql`(${table.status} = 'pending' and ${table.sha256} is null and ${table.sizeBytes} is null)
       or (${table.status} = 'stored'
           and ${table.sha256} ~ '^[0-9a-f]{64}$'
           and ${table.sizeBytes} is not null
           and ${table.sizeBytes} > 0
           and ${table.sizeBytes} <= 104857600)`,
    ),
  ],
);
