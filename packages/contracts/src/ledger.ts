import { z } from 'zod';

/**
 * Ledger API schemas (architecture §7, §23).
 *
 * Amounts cross the wire as integer-poisha strings, never numbers (see
 * approvals.ts for why). Dates are `YYYY-MM-DD` business dates in Asia/Dhaka;
 * months are `YYYY-MM`.
 */

const ISO_DATE = /^\d{4}-\d{2}-\d{2}$/;

function realDate(value: string): boolean {
  if (!ISO_DATE.test(value)) return false;
  const [y, m, d] = value.split('-').map(Number);
  const date = new Date(Date.UTC(y ?? 0, (m ?? 1) - 1, d ?? 1));
  return (
    date.getUTCFullYear() === y && date.getUTCMonth() === (m ?? 1) - 1 && date.getUTCDate() === d
  );
}

export const businessDateSchema = z
  .string()
  .refine(realDate, 'Dates are YYYY-MM-DD calendar dates.');

export const monthSchema = z.string().regex(/^\d{4}-(0[1-9]|1[0-2])$/, 'Months are YYYY-MM.');

/** A strictly positive integer-poisha string that fits §7's ±9e15 bound. */
export const positivePoishaSchema = z
  .string()
  .max(16, 'Amounts are integer poisha, sent as a decimal string.')
  .regex(/^[1-9]\d*$/, 'Amounts are positive integer poisha, sent as a decimal string.')
  // Guarded: Zod runs every check, and BigInt throws on what the regex refused.
  .refine(
    (value) => !/^\d+$/.test(value) || BigInt(value) <= 9_000_000_000_000_000n,
    'That amount is out of range.',
  );

export const ledgerIdSchema = z.string().uuid('No such record.');

/**
 * Cash in (§7 posting rules): money received into a wallet, credited to an
 * other-income category. `entryId` is generated by the client once per entry
 * and makes a retried submit post one journal, not two.
 */
export const cashInSchema = z.object({
  entryId: z.string().uuid(),
  walletAccountId: z.string().uuid(),
  incomeAccountId: z.string().uuid(),
  amountPoisha: positivePoishaSchema,
  memo: z.string().trim().max(500).optional(),
});
export type CashInInput = z.infer<typeof cashInSchema>;

export const closePeriodSchema = z.object({ month: monthSchema });
export type ClosePeriodInput = z.infer<typeof closePeriodSchema>;

export const reopenPeriodSchema = z.object({
  month: monthSchema,
  reason: z.string().trim().min(1, 'Say why the period must reopen.').max(500),
});
export type ReopenPeriodInput = z.infer<typeof reopenPeriodSchema>;

/** A date range, both ends inclusive. `from` defaults to the start of time. */
export const dateRangeSchema = z
  .object({
    from: businessDateSchema.optional(),
    to: businessDateSchema,
  })
  .refine((value) => value.from === undefined || value.from <= value.to, {
    message: '`from` must not be after `to`.',
    path: ['from'],
  });

export const trialBalanceQuerySchema = z.object({ asOf: businessDateSchema });

export const dayBookQuerySchema = z
  .object({ from: businessDateSchema, to: businessDateSchema })
  .refine((value) => value.from <= value.to, {
    message: '`from` must not be after `to`.',
    path: ['from'],
  });

export const PARTY_TYPE_VALUES = [
  'supplier',
  'courier',
  'reseller',
  'investor',
  'employee',
  'lender',
] as const;

export const partyBalanceQuerySchema = z.object({
  asOf: businessDateSchema,
  partyType: z.enum(PARTY_TYPE_VALUES).optional(),
  partyId: z.string().uuid().optional(),
});
